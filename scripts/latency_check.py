"""Measured latency of each configuration: look-ahead of the trained model, streaming delay, per-hop compute.

1. Look-ahead (prefix test with the trained network, offline path): two inputs that agree up to sample p0 and
   differ afterwards; the earliest output sample that differs gives how far the system looks into the future.
   The worst case over positions p0 within a hop is reported. Configs without a checkpoint use random weights
   (the look-ahead depends on the framing, not on the weights).
2. Streaming delay (impulse test): an impulse through the frame-by-frame implementation with a unit mask; the
   output peak position gives the delay relative to the input. Worst-case algorithmic latency = delay + R - 1
   (a sample can wait R - 1 samples for its input block to complete).
3. Per-hop compute from results/latency_benchmark.csv (ONNX Runtime, one thread): P50 / P95 / P99 per hop and
   the share of hops that exceeded the hop duration (deadline misses).

Usage: python -I scripts/latency_check.py
Outputs: results/latency_check.md, results/latency_check.csv
"""
from __future__ import annotations

import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO))

import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402
import torch  # noqa: E402

from dwmss.config import load_config  # noqa: E402
from dwmss.model import MaskNet  # noqa: E402
from dwmss.stft import DualWindowSTFT  # noqa: E402
from dwmss.streaming import StreamingSeparator  # noqa: E402

SR = 44100
CONFIGS = ["A_sym1024", "B_sym256", "C_dual", "E_sym128", "D_dual_2p9ms"]


def look_ahead(model, stft, length=40000, p0_base=20000, steps=16) -> int:
    torch.manual_seed(0)
    base = torch.randn(1, length) * 0.1

    @torch.no_grad()
    def process(x):
        X = stft.analysis(x)
        m, _ = model(X, stft.window_energy)
        return stft.synthesis(m * X, length)[0]

    y0 = process(base)
    worst = 0
    for off in range(0, stft.R, max(1, stft.R // steps)):
        p0 = p0_base + off
        x2 = base.clone()
        x2[0, p0:] = torch.randn(length - p0) * 0.1
        diff = torch.nonzero((y0 - process(x2)).abs() > 0)
        first = int(diff[0]) if len(diff) else length
        worst = max(worst, p0 - first)
    return worst


def streaming_delay(stft) -> int:
    st = StreamingSeparator(None, stft)
    st._mask = lambda X: np.ones(X.shape, dtype=np.float32)  # identity: output = delayed input
    x = np.zeros(6000, np.float32)
    x[3001] = 1.0
    y = st.run(np.concatenate([x, np.zeros(st.output_delay + stft.R, np.float32)]))
    return int(np.argmax(np.abs(y))) - 3001


def main():
    torch.set_num_threads(2)
    bench = REPO / "results" / "latency_benchmark.csv"
    b = pd.read_csv(bench) if bench.exists() else None
    rows = []
    for name in CONFIGS:
        cfg = load_config(str(REPO / "configs" / f"{name}.yaml"))
        stft = DualWindowSTFT(cfg["stft"]["n_analysis"], cfg["stft"]["n_synthesis"])
        model = MaskNet(**cfg["model"]).eval()
        ck = REPO / "runs" / f"{name}_seed0" / "best.pt"
        weights = "trained" if ck.exists() else "random"
        if ck.exists():
            model.load_state_dict(torch.load(ck, map_location="cpu", weights_only=False)["model"])
        la = look_ahead(model, stft)
        delay = streaming_delay(stft)
        r = {"config": name, "N": stft.N, "M": stft.M, "hop": stft.R, "weights": weights,
             "look_ahead_samples": la, "look_ahead_ms": 1000 * la / SR, "bound_samples": stft.M - 1,
             "streaming_delay_samples": delay, "worst_latency_samples": delay + stft.R - 1,
             "worst_latency_ms": 1000 * (delay + stft.R - 1) / SR, "hop_ms": 1000 * stft.R / SR}
        if b is not None:
            m = b[(b["config"] == name) & (b["backend"] == "onnx")]
            if len(m):
                m = m.iloc[0]
                r.update({"p50_ms": m["p50_us"] / 1000, "p95_ms": m["p95_us"] / 1000, "p99_ms": m["p99_us"] / 1000,
                          "deadline_miss_rate": m["deadline_miss_rate"], "bench_weights": m["weights"]})
        rows.append(r)
        print(r, flush=True)
    df = pd.DataFrame(rows)
    df.to_csv(REPO / "results" / "latency_check.csv", index=False)
    L = ["# Measured latency", "",
         "Generated by `scripts/latency_check.py`. Algorithmic latency is derived from the framing (synthesis window "
         "M, hop R = M/2) and checked here on the actual implementation.", "",
         "| config | N / M / hop | measured look-ahead (trained model) | bound M − 1 | streaming delay | worst-case "
         "algorithmic latency | per-hop compute P50 / P95 / P99 (hop) | hops over the deadline |",
         "|---|---|---|---|---|---|---|---|"]
    for _, r in df.iterrows():
        comp = (f"{r['p50_ms']:.2f} / {r['p95_ms']:.2f} / {r['p99_ms']:.2f} ms ({r['hop_ms']:.2f} ms)"
                if "p99_ms" in r and pd.notna(r.get("p99_ms")) else "–")
        miss = f"{100 * r['deadline_miss_rate']:.2f}%" if "deadline_miss_rate" in r and pd.notna(r.get("deadline_miss_rate")) else "–"
        L.append(f"| {r['config']}{'' if r['weights'] == 'trained' else ' (random weights)'} | {r['N']} / {r['M']} / {r['hop']} | "
                 f"{r['look_ahead_samples']} samples ({r['look_ahead_ms']:.2f} ms) | {r['bound_samples']} | "
                 f"{r['streaming_delay_samples']} samples | {r['worst_latency_samples']} samples ({r['worst_latency_ms']:.2f} ms) | "
                 f"{comp} | {miss} |")
    L += ["", "- Look-ahead: worst case over 16 positions within a hop; the measured value stays below the M − 1 bound "
              "because the synthesis window is zero at its edge.",
          "- Streaming delay: impulse through the frame-by-frame implementation (`dwmss/streaming.py`); worst-case "
              "algorithmic latency = delay + hop − 1 samples = M − 1.",
          "- Per-hop compute: full pipeline (STFT, network, mask, iSTFT) with ONNX Runtime on one CPU thread "
              "(`results/latency_benchmark.md`). The real-time factor is the mean; the P99 and the share of hops over "
              "the hop duration show whether individual callbacks meet the deadline. Measured in Python on a shared "
              "cluster node; a deployed system would run in a dedicated real-time audio thread.",
          "- End-to-end latency through an audio interface (driver and device buffers) is not measured."]
    (REPO / "results" / "latency_check.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
